 case when p.special_offer then round((round((b.base_price*sz.size_ml*(1-(sz.ordinality-1)*0.045))/10)*10)*1.18/10)*10
 else round((b.base_price*sz.size_ml*(1-(sz.ordinality-1)*0.045))/10)*10 end,
