-- Atomic administrator product + variant write. Product and all variants commit or roll back together.
create or replace function public.admin_save_product(p_product jsonb,p_variants jsonb) returns jsonb language plpgsql security definer set search_path=public as $$
declare saved public.products;
begin
 if not public.is_admin() then raise exception 'Administrator access required.' using errcode='42501'; end if;
 if coalesce(jsonb_typeof(p_variants),'')<>'array' then raise exception 'Variants must be an array.'; end if;
 if jsonb_array_length(p_variants)=0 then raise exception 'Add at least one size and price variant.'; end if;
 if p_product ? 'id' and nullif(p_product->>'id','') is not null then
   update public.products set slug=p_product->>'slug',name=p_product->>'name',brand=coalesce(p_product->>'brand','DEQANT'),category=p_product->>'category',
    description=coalesce(p_product->>'description',''),notes=coalesce(p_product->>'notes',''),family=coalesce(p_product->>'family',''),
    image_url=coalesce(p_product->>'image_url',''),image_urls=coalesce(array(select jsonb_array_elements_text(coalesce(p_product->'image_urls','[]'::jsonb))),'{}'),
    best_seller=coalesce((p_product->>'best_seller')::boolean,false),special_offer=coalesce((p_product->>'special_offer')::boolean,false),
    featured=coalesce((p_product->>'featured')::boolean,false),new_arrival=coalesce((p_product->>'new_arrival')::boolean,true),
    active=coalesce((p_product->>'active')::boolean,false),updated_at=now()
   where id=(p_product->>'id')::bigint returning * into saved;
   if not found then raise exception 'Product not found.'; end if;
 else
   insert into public.products(slug,name,brand,category,description,notes,family,image_url,image_urls,best_seller,special_offer,featured,new_arrival,active)
   values(p_product->>'slug',p_product->>'name',coalesce(p_product->>'brand','DEQANT'),p_product->>'category',coalesce(p_product->>'description',''),coalesce(p_product->>'notes',''),coalesce(p_product->>'family',''),coalesce(p_product->>'image_url',''),coalesce(array(select jsonb_array_elements_text(coalesce(p_product->'image_urls','[]'::jsonb))),'{}'),coalesce((p_product->>'best_seller')::boolean,false),coalesce((p_product->>'special_offer')::boolean,false),coalesce((p_product->>'featured')::boolean,false),coalesce((p_product->>'new_arrival')::boolean,true),coalesce((p_product->>'active')::boolean,false)) returning * into saved;
 end if;
 delete from public.product_variants where product_id=saved.id;
 insert into public.product_variants(product_id,size_ml,price,original_price,stock,sku,active)
 select saved.id,v.size_ml,v.price,v.original_price,v.stock,coalesce(nullif(v.sku,''),upper(saved.slug||'-'||v.size_ml||'ml')),coalesce(v.active,true)
 from jsonb_to_recordset(p_variants) as v(size_ml integer,price integer,original_price integer,stock integer,sku text,active boolean);
 return to_jsonb(saved);
end; $$;

-- Guest carts are accessed only through RPCs. The opaque UUID is a capability token.
create or replace function public.cart_read(p_token uuid) returns jsonb language plpgsql security definer set search_path=public as $$
declare c public.carts; result jsonb;
begin
 select * into c from public.carts where token=p_token;
 if not found then insert into public.carts(token) values(coalesce(p_token,gen_random_uuid())) returning * into c; end if;
 select jsonb_build_object('token',c.token,'items',coalesce(jsonb_agg(jsonb_build_object(
  'id',ci.id,'quantity',ci.quantity,'variant',jsonb_build_object('id',v.id,'sizeMl',v.size_ml,'price',v.price,'originalPrice',v.original_price,'stock',v.stock),
  'product',jsonb_build_object('id',p.id,'slug',p.slug,'name',p.name,'brand',p.brand,'category',p.category,'imageUrl',p.image_url),
  'lineTotal',v.price*ci.quantity) order by ci.created_at) filter(where ci.id is not null),'[]'::jsonb),
  'subtotal',coalesce(sum(v.price*ci.quantity),0),'count',coalesce(sum(ci.quantity),0)) into result
 from public.cart_items ci join public.product_variants v on v.id=ci.variant_id join public.products p on p.id=v.product_id where ci.cart_id=c.id;
 return result;
end; $$;

create or replace function public.cart_add(p_token uuid,p_variant_id bigint,p_quantity integer) returns jsonb language plpgsql security definer set search_path=public as $$
declare c public.carts; v public.product_variants; next_qty integer;
begin
 perform public.consume_rate_limit('cart_add',120,60);
 if p_quantity<1 or p_quantity>10 then raise exception 'Quantity must be between 1 and 10.'; end if;
 select * into v from public.product_variants where id=p_variant_id and active for update;
 if not found or v.stock<1 then raise exception 'This size is currently out of stock.'; end if;
 if not exists(select 1 from public.products where id=v.product_id and active) then raise exception 'This fragrance is not available.'; end if;
 select * into c from public.carts where token=p_token;
 if not found then insert into public.carts(token) values(coalesce(p_token,gen_random_uuid())) returning * into c; end if;
 insert into public.cart_items(cart_id,variant_id,quantity) values(c.id,v.id,p_quantity)
 on conflict(cart_id,variant_id) do update set quantity=public.cart_items.quantity+excluded.quantity returning quantity into next_qty;
 if next_qty>least(v.stock,10) then raise exception 'Not enough stock available. Only % remain.',v.stock; end if;
 return public.cart_read(c.token);
end; $$;

create or replace function public.cart_update(p_token uuid,p_item_id bigint,p_quantity integer) returns jsonb language plpgsql security definer set search_path=public as $$
declare c public.carts; v public.product_variants;
begin
 if p_quantity<1 or p_quantity>10 then raise exception 'Quantity must be between 1 and 10.'; end if;
 select * into c from public.carts where token=p_token; if not found then raise exception 'Cart not found.'; end if;
 select pv.* into v from public.cart_items ci join public.product_variants pv on pv.id=ci.variant_id where ci.id=p_item_id and ci.cart_id=c.id;
 if not found or p_quantity>v.stock then raise exception 'Requested quantity is unavailable.'; end if;
 update public.cart_items set quantity=p_quantity where id=p_item_id and cart_id=c.id;
 return public.cart_read(c.token);
end; $$;

create or replace function public.cart_remove(p_token uuid,p_item_id bigint) returns jsonb language plpgsql security definer set search_path=public as $$
declare c public.carts;
begin select * into c from public.carts where token=p_token; if found then delete from public.cart_items where id=p_item_id and cart_id=c.id; end if; return public.cart_read(p_token); end; $$;

-- All checkout calculations and inventory writes happen inside one PostgreSQL transaction.
create or replace function public.place_order(p_token uuid,p_idempotency_key uuid,p_customer_name text,p_phone text,p_email text,p_district text,p_area text,p_address text,p_instructions text,p_zone_id bigint) returns jsonb language plpgsql security definer set search_path=public as $$
declare c public.carts; z public.delivery_zones; o public.orders; line record; sub integer:=0; onum text;
begin
 perform public.consume_rate_limit('checkout',8,600);
 if length(trim(p_customer_name))<2 or length(trim(p_phone))<8 or length(trim(p_phone))>30 or length(trim(p_address))<8 then raise exception 'Please check your name, phone and delivery address.'; end if;
 select * into o from public.orders where idempotency_key=p_idempotency_key; if found then return jsonb_build_object('orderNumber',o.order_number,'total',o.total); end if;
 select * into c from public.carts where token=p_token; if not found then raise exception 'Your cart is empty.'; end if;
 if not exists(select 1 from public.cart_items where cart_id=c.id) then raise exception 'Your cart is empty.'; end if;
 select * into z from public.delivery_zones where id=p_zone_id and active; if not found then raise exception 'Select a valid delivery zone.'; end if;
 for line in select ci.id as cart_item_id,ci.quantity,v.id as variant_id,v.size_ml,v.price,v.original_price,v.stock,p.id as product_id,p.name,p.brand,p.category,p.active as product_active,v.active as variant_active
  from public.cart_items ci join public.product_variants v on v.id=ci.variant_id join public.products p on p.id=v.product_id where ci.cart_id=c.id for update of v loop
   if not line.product_active or not line.variant_active or line.stock<line.quantity then raise exception 'Stock changed while you were checking out. Please review your cart.'; end if;
   sub:=sub+(line.price*line.quantity);
 end loop;
 onum:='DQ-'||to_char(now(),'YYYYMMDD')||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,6));
 insert into public.orders(order_number,idempotency_key,customer_name,phone,email,district,area,address,instructions,delivery_zone_id,subtotal,delivery_fee,total)
 values(onum,p_idempotency_key,trim(p_customer_name),trim(p_phone),nullif(trim(p_email),''),trim(p_district),trim(p_area),trim(p_address),nullif(trim(p_instructions),''),z.id,sub,z.fee,sub+z.fee) returning * into o;
 for line in select ci.quantity,v.id as variant_id,v.size_ml,v.price,v.original_price,p.id as product_id,p.name,p.brand,p.category
  from public.cart_items ci join public.product_variants v on v.id=ci.variant_id join public.products p on p.id=v.product_id where ci.cart_id=c.id for update of v loop
   update public.product_variants set stock=stock-line.quantity where id=line.variant_id;
   insert into public.order_items(order_id,product_id,variant_id,product_name,brand,category,size_ml,quantity,unit_price,original_price,line_total)
   values(o.id,line.product_id,line.variant_id,line.name,line.brand,line.category,line.size_ml,line.quantity,line.price,line.original_price,line.price*line.quantity);
 end loop;
 delete from public.cart_items where cart_id=c.id;
 return jsonb_build_object('orderNumber',o.order_number,'total',o.total);
end; $$;

create or replace function public.track_order(p_order_number text,p_phone text) returns jsonb language plpgsql security definer set search_path=public as $$
declare o public.orders;
begin
 perform public.consume_rate_limit('tracking',30,600);
 select * into o from public.orders where order_number=upper(trim(p_order_number)) and phone=trim(p_phone);
 if not found then raise exception 'No matching order. Check your order ID and phone number.'; end if;
 return jsonb_build_object('orderNumber',o.order_number,'status',o.status,'total',o.total,'created_at',o.created_at);
end; $$;

create or replace function public.order_by_phone(p_order_number text,p_phone text) returns jsonb language plpgsql security definer set search_path=public as $$
declare o public.orders; items jsonb;
begin
 perform public.consume_rate_limit('order_lookup',30,600);
 select * into o from public.orders where order_number=upper(trim(p_order_number)) and phone=trim(p_phone);
 if not found then raise exception 'We could not find an order with those details.'; end if;
 select coalesce(jsonb_agg(jsonb_build_object('id',i.id,'productName',i.product_name,'brand',i.brand,'category',i.category,'sizeMl',i.size_ml,'quantity',i.quantity,'unitPrice',i.unit_price,'originalPrice',i.original_price,'lineTotal',i.line_total)),'[]'::jsonb)
 into items from public.order_items i where i.order_id=o.id;
 return jsonb_build_object('order',jsonb_build_object('id',o.id,'orderNumber',o.order_number,'customerName',o.customer_name,'phone',o.phone,'email',o.email,'district',o.district,'area',o.area,'address',o.address,'instructions',o.instructions,'subtotal',o.subtotal,'deliveryFee',o.delivery_fee,'total',o.total,'status',o.status,'created_at',o.created_at),'items',items);
end; $$;

