create or replace function public.consume_rate_limit(p_scope text,p_limit integer,p_window_seconds integer) returns void language plpgsql security definer set search_path=public as $$
declare hdr jsonb; client_ip text; k text; now_at timestamptz:=clock_timestamp(); existing public.api_rate_limits;
begin
 hdr:=coalesce(nullif(current_setting('request.headers',true),''),'{}')::jsonb;
 client_ip:=coalesce(hdr->>'cf-connecting-ip',split_part(coalesce(hdr->>'x-forwarded-for','unknown'),',',1),'unknown');
 k:=p_scope||':'||md5(client_ip);
 insert into public.api_rate_limits(bucket_key,window_started_at,request_count) values(k,now_at,1)
 on conflict(bucket_key) do update set window_started_at=case when public.api_rate_limits.window_started_at+make_interval(secs=>p_window_seconds)<=now_at then now_at else public.api_rate_limits.window_started_at end,
 request_count=case when public.api_rate_limits.window_started_at+make_interval(secs=>p_window_seconds)<=now_at then 1 else public.api_rate_limits.request_count+1 end
 returning * into existing;
 if existing.request_count>p_limit then raise exception 'Too many requests. Please wait before trying again.' using errcode='P0001'; end if;
end; $$;
revoke all on function public.consume_rate_limit(text,integer,integer) from public,anon,authenticated;
create or replace function public.submit_contact(p_name text,p_email text,p_message text) returns jsonb language plpgsql security definer set search_path=public as $$
begin
 perform public.consume_rate_limit('contact',5,3600);
 if length(trim(p_name))<2 or length(trim(p_name))>180 or length(trim(p_message))<10 or length(trim(p_message))>3000 or p_email !~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'Please enter valid contact details and a message.'; end if;
 insert into public.contact_messages(name,email,message) values(trim(p_name),trim(p_email),trim(p_message));
 return jsonb_build_object('ok',true);
end; $$;


