create or replace function public.validate_coupon(p_code text) returns jsonb
language plpgsql security definer set search_path=public as $$
declare c public.coupons;
begin
 perform public.consume_rate_limit('coupon_validate',30,600);
 if nullif(trim(p_code),'') is null then raise exception 'Enter a coupon code.'; end if;
 select * into c from public.coupons where code=upper(trim(p_code)) and active
  and (expires_at is null or expires_at>now()) and (usage_limit is null or usage_count<usage_limit);
 if not found then raise exception 'This coupon is invalid, expired, or has reached its usage limit.'; end if;
 return jsonb_build_object('code',c.code,'discountPercent',c.discount_percent);
end; $$;
revoke all on function public.validate_coupon(text) from public;
grant execute on function public.validate_coupon(text) to anon,authenticated;
