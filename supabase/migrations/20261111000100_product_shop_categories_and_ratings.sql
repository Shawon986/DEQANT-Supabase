-- DEQANT shop-by categories and customer star ratings.
alter table public.products add column if not exists shop_categories text[] not null default '{}';
create index if not exists products_shop_categories_gin_idx on public.products using gin (shop_categories);
create table if not exists public.product_ratings (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product_id, user_id)
);
create index if not exists product_ratings_product_idx on public.product_ratings(product_id);
alter table public.product_ratings enable row level security;
create policy "Public can read product ratings" on public.product_ratings for select to anon, authenticated using (true);
create policy "Customers can create their own rating" on public.product_ratings for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Customers can update their own rating" on public.product_ratings for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
grant select on public.product_ratings to anon, authenticated;
grant insert, update on public.product_ratings to authenticated;
grant usage, select on sequence public.product_ratings_id_seq to authenticated;
create or replace view public.product_rating_summary with (security_invoker = true) as
select product_id, round(avg(rating)::numeric, 1) as average_rating, count(*)::integer as rating_count
from public.product_ratings group by product_id;
grant select on public.product_rating_summary to anon, authenticated;
